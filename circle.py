import math


def area(r):
    '''
    Вычисляет площадь круга по формуле S = πR².

    Параметры:
        r (int | float): радиус круга, r >= 0

    Возвращаемое значение:
        float: площадь круга
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Вычисляет длину окружности (периметр круга) по формуле P = 2πR.

    Параметры:
        r (int | float): радиус круга, r >= 0

    Возвращаемое значение:
        float: длина окружности
    '''
    return 2 * math.pi * r
