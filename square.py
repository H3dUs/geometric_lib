
def area(a):
    '''
    Вычисляет площадь квадрата по формуле S = a².

    Параметры:
        a (int | float): длина стороны квадрата, a >= 0

    Возвращаемое значение:
        int | float: площадь квадрата
    '''
    return a * a


def perimeter(a):
    '''
    Вычисляет периметр квадрата по формуле P = 4a.

    Параметры:
        a (int | float): длина стороны квадрата, a >= 0

    Возвращаемое значение:
        int | float: периметр квадрата
    '''
    return 4 * a
